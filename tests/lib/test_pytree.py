"""Differential tests: shax's pure-Python pytree vs jaxlib's C++ pytree.

Expected outputs come from fixtures/pytree_cases.json, generated from real
jaxlib 0.12.0.1 by gen_pytree_fixture.py. The cases themselves (and the
normalization of results / exceptions / warnings) live in _pytree_cases.py.
"""
import importlib.util
import json
import os
import sys

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

import _pytree_cases  # noqa: E402


def _load_pytree():
  # Load straight from the file so these tests don't depend on the rest of
  # `shax.jax` importing cleanly. Register it in sys.modules so that pickling
  # (which looks classes up by module name) works.
  name = "_shax_pytree"
  if name in sys.modules:
    return sys.modules[name]
  path = os.path.join(_HERE, os.pardir, os.pardir, "shax", "jax", "_src",
                      "lib", "pytree.py")
  spec = importlib.util.spec_from_file_location(name, path)
  mod = importlib.util.module_from_spec(spec)
  sys.modules[name] = mod
  spec.loader.exec_module(mod)
  return mod


P = _load_pytree()

with open(os.path.join(_HERE, "fixtures", "pytree_cases.json"),
          encoding="utf-8") as _f:
  _EXPECTED = json.load(_f)["cases"]

_CASES = _pytree_cases.make_cases(P)


def test_case_names_match_fixture():
  assert sorted(n for n, _ in _CASES) == sorted(_EXPECTED)


# Known, deliberate differences from the C++ implementation.
_KNOWN_DIFFERENCES = {
    # The C++ hash mixes in the per-registry Registration pointer for
    # dataclass nodes while equality ignores it, so equal treedefs from
    # different registries hash differently. We keep hash consistent with eq.
    **{f"hash_consistent/{n}": "dataclass hash ignores registry"
       for n in ("dc", "dc_nested", "dc2", "dc_meta")},
    # Messages generated by CPython itself name nanobind types by their full
    # dotted tp_name ('jaxlib._jax.pytree.SequenceKey'); ours are plain
    # Python classes, and missing-argument errors come from Python, not
    # nanobind.
    "reduce_unnamed": "CPython type name in AttributeError",
    "key_lt": "CPython type name in TypeError",
    "key_set_attr": "CPython type name in AttributeError",
    "key_ctor_errors": "missing-argument errors come from Python",
}


@pytest.mark.parametrize("name,thunk", _CASES, ids=[n for n, _ in _CASES])
def test_against_jaxlib(name, thunk):
  got = _pytree_cases.run_case(thunk)
  if name in _KNOWN_DIFFERENCES:
    if got != _EXPECTED[name]:
      pytest.xfail(_KNOWN_DIFFERENCES[name])
  assert got == _EXPECTED[name]
